#!/usr/bin/env node
/**
 * Build frontend/src/shared/assetManifest.ts from the files in
 * frontend/static/ui-assets/.
 *
 * The manifest maps logical asset paths (e.g. 'generated/scene_yungang_day.webp')
 * to Vite-imported URLs via import.meta.glob, so assets referenced through
 * the manifest get content-hashed filenames and immutable cache headers.
 *
 * Usage:
 *   node scripts/build-asset-manifest.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const STATIC_DIR = path.join(ROOT, 'frontend', 'static', 'ui-assets');
const OUT_FILE = path.join(ROOT, 'frontend', 'src', 'shared', 'assetManifest.ts');

const IMAGE_EXT = /\.(webp|avif|png)$/i;

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

const files = [...walk(STATIC_DIR)]
  .map((full) => path.relative(STATIC_DIR, full).replace(/\\/g, '/'))
  .filter((rel) => IMAGE_EXT.test(rel))
  .sort();

const logicalPaths = files.map((rel) => `  '${rel}'`).join(',\n');

const content = `// Auto-generated by scripts/build-asset-manifest.mjs
// Do not edit by hand.

const imports = import.meta.glob('/ui-assets/**/*.{webp,avif,png}', { eager: true, import: 'default' });

const manifest: Record<string, string> = {};
Object.entries(imports).forEach(([path, url]) => {
  manifest[path.replace('/ui-assets/', '')] = url as string;
});

export function resolveAsset(path: string, fallback?: string): string {
  return manifest[path] ?? (fallback ? manifest[fallback] ?? fallback : path);
}

// Logical paths present when this manifest was generated.
export const knownAssetPaths = [
${logicalPaths}
] as const;
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, content, 'utf8');

console.log(`Generated ${path.relative(ROOT, OUT_FILE)} with ${files.length} assets.`);
